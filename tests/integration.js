(async () => {
  if (!testMode) return;
  const sleep = (ms = 350) => new Promise((resolve) => setTimeout(resolve, ms));
  const check = (condition, text) => {
    if (!condition) throw new Error(text);
    results.textContent += `PASS · ${text}\n`;
  };
  const root = () => document.querySelector('[data-sleep-timer]').shadowRoot;
  const status = () => root().querySelector('.status').textContent;
  const choose = (seconds) => {
    const input = root().querySelector(`input[value="${seconds}"]`);
    input.checked = true;
    input.dispatchEvent(new Event('change', { bubbles: true }));
  };
  try {
    await sleep();
    check(document.querySelector('.right').firstElementChild.matches('[data-sleep-timer]'), 'Buton sağ grubun en başında');
    check(document.querySelectorAll('[data-sleep-timer]').length === 1, 'Tek buton ekleniyor');
    check(root().querySelectorAll('input').length === 10, 'Kapalı, 6 dakika seçeneği ve 3 test süresi');
    root().querySelector('.trigger').click(); await sleep(50);
    check(root().querySelector('.panel').matches(':popover-open'), 'Menü açılıyor');
    root().querySelector('.close').click();
    check(!root().querySelector('.panel').matches(':popover-open'), 'Menü kapanıyor');
    choose(10);
    fixture.clock += 20000; await sleep();
    check(status().includes('00:10') && status().includes('Bekliyor'), 'Duraklatılmış videoda sayaç sabit');
    await media.play(); fixture.clock += 3000; await sleep();
    check(status().includes('00:07'), 'Oynatınca süre azalıyor');
    media.pause(); fixture.clock += 30000; await sleep();
    check(status().includes('00:07'), 'Duraklatınca kalan süre korunuyor');
    await media.play();
    media.dispatchEvent(new Event('waiting')); fixture.clock += 5000; await sleep();
    check(status().includes('00:07'), 'Yükleme beklemesi sayılmıyor');
    media.dispatchEvent(new Event('playing')); fixture.clock += 1000; await sleep();
    check(status().includes('00:06'), 'Yükleme sonrası sayaç devam ediyor');
    fixture.state.seeking = true; media.dispatchEvent(new Event('seeking'));
    fixture.clock += 5000; await sleep();
    check(status().includes('00:06'), 'İleri/geri sarma beklemesi sayılmıyor');
    fixture.state.seeking = false; media.dispatchEvent(new Event('seeked'));
    choose(5); const before = fixture.pauses;
    fixture.clock += 6000; await sleep();
    check(media.paused && fixture.pauses === before + 1, 'Süre bitince video bir kez duraklatılıyor');
    check(status().includes('Süre doldu'), 'Bitiş durumu gösteriliyor');
    await media.play(); await sleep();
    check(!media.paused, 'Kullanıcı süre dolduktan sonra yeniden oynatabiliyor');
    choose(30); fixture.clock += 1000; await sleep();
    choose(0); fixture.clock += 60000; await sleep();
    check(!media.paused && status().includes('kapalı'), 'Kapalı seçeneği durdurma işlemini iptal ediyor');
    choose(30);
    const oldHost = document.querySelector('[data-sleep-timer]');
    oldHost.remove(); await sleep();
    check(document.querySelectorAll('[data-sleep-timer]').length === 1, 'Kontrol kaldırıldığında tekrar ekleniyor');
    check(status().includes('00:30'), 'Kontrol yeniden eklenirken süre korunuyor');
    const group = document.querySelector('.right');
    const replacement = group.cloneNode(true);
    replacement.querySelector('[data-sleep-timer]').remove();
    group.replaceWith(replacement); await sleep();
    check(document.querySelectorAll('[data-sleep-timer]').length === 1 && replacement.firstElementChild.matches('[data-sleep-timer]'), 'Kontrol grubu yeniden oluşturulunca doğru yere bağlanıyor');
    history.pushState({}, '', '/watch/200?test=1'); await sleep(1100);
    check(status().includes('kapalı'), 'Yeni videoya geçince sayaç taşınmıyor');
    choose(30); media.dispatchEvent(new Event('ended')); await sleep();
    check(status().includes('Video bitti'), 'Video sonunda zamanlayıcı temizleniyor');
    history.pushState({}, '', '/browse?test=1'); await sleep(1100);
    check(!document.querySelector('[data-sleep-timer]'), 'İzleme sayfasından ayrılınca kontrol kaldırılıyor');
    history.pushState({}, '', '/watch/100?test=1'); await sleep(1100);
    check(document.querySelectorAll('[data-sleep-timer]').length === 1, 'SPA ile oynatıcıya dönünce kontrol ekleniyor');
    const pagehide = new Event('pagehide');
    Object.defineProperty(pagehide, 'persisted', { value: true });
    window.dispatchEvent(pagehide);
    window.dispatchEvent(new Event('pageshow'));
    choose(10); fixture.clock += 1000; await sleep();
    check(status().includes('00:09'), 'Önbellekten geri dönülen sayfada yeni sayaç çalışıyor');
    results.textContent += '\nALL PASSED · Sentetik medya durumları; gerçek Netflix testi değildir.';
    document.title = 'PASS · Sleep Timer integration';
  } catch (error) {
    results.textContent += `\nFAIL · ${error.message}`;
    document.title = 'FAIL · Sleep Timer integration';
  }
})();
